"""Syntax cases from fastapi/full-stack-fastapi-template at 77e550a73bb49dd2967622c5ed11bf7a49603c93.

The fixture uses small synthetic definitions, with no repository imports or execution.
"""
import ast
import unittest

import default_flow
import service_flow
import structure_index


class DeclaredDefaults(unittest.TestCase):
    def test_prefix_requires_settings_declaration_instance_and_router_mount(self):
        files = {
            'src/main.py': """from fastapi import FastAPI
from api import router
from config import settings
app = FastAPI()
app.include_router(router, prefix=settings.BASE)
""",
            'src/config.py': """from pydantic_settings import BaseSettings
class Config(BaseSettings):
    BASE: str = '/v1'
settings = Config()
""",
            'src/api.py': """from fastapi import APIRouter
router = APIRouter(prefix='/things')
@router.get('/')
def things(): pass
"""}
        facts = {}
        external = {'routers':{}, 'mounts':[]}
        for file, source in files.items():
            tree = ast.parse(source)
            facts[file] = default_flow.python_facts(tree)
            service_flow.python_routes(tree, file, external)
        row, = default_flow.default_routes(facts, external['routers'])
        self.assertEqual((row['basis'],row['path']),('declared_defaults','/v1/things/'))
        self.assertIn({'file':'src/config.py','line':3},row['mounts'])
        self.assertEqual(row['server'],{'file':'src/api.py','line':3,'function':'things'})
        # Constructor overrides, unresolved expressions and non-settings classes do not prove this default.
        for altered in [files['src/config.py'].replace('Config()', "Config(BASE='/custom')"),
                        files['src/config.py'].replace("'/v1'",'read_prefix()'),
                        files['src/config.py'].replace('from pydantic_settings','from unrelated')]:
            facts['src/config.py'] = default_flow.python_facts(ast.parse(altered))
            self.assertEqual(default_flow.default_routes(facts,external['routers']),[])

    def test_generated_sdk_requires_local_exported_client_and_factory(self):
        generated = '// This file is auto-generated by @hey-api/openapi-ts\n'
        inputs = {'sdk.ts':"""import {client} from './client.gen';
export class Things {
 static load(options) {
   return (options?.client ?? client).get({url:'/v1/things/', ...options});
 }
}
""",
                  'client.gen.ts':"""import {createClient} from './runtime';
export const client = createClient({});
""",
                  'runtime/index.ts':"export { createClient } from './impl';",
                  'runtime/impl.ts':"export const createClient = () => ({});"}
        parsed = {file:default_flow.sdk_facts(structure_index._parser('typescript').parse(
                  (generated+source).encode()).root_node,file) for file,source in inputs.items()}
        row, = default_flow.sdk_requests(parsed)
        self.assertEqual((row['basis'],row['method'],row['path']),('declared_defaults','GET','/v1/things/'))
        self.assertIn({'file':'runtime/impl.ts','line':2},row['evidence'])
        del parsed['runtime/impl.ts']
        self.assertEqual(default_flow.sdk_requests(parsed),[])
